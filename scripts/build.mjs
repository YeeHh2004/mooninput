import {execFileSync} from 'node:child_process';
import {mkdirSync, copyFileSync, readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {homedir} from 'node:os';
import {join} from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const version=JSON.parse(readFileSync(new URL('../package.json',import.meta.url),'utf8')).version;
const versionText = execFileSync('moon', ['version','--all'], {cwd:root,encoding:'utf8'});
const compilerVersion = execFileSync('moonc', ['-v'], {cwd:root,encoding:'utf8'}).trim();
const toolchain = /^v([^\s]+)/.exec(compilerVersion)?.[1];
if (!toolchain) throw new Error(`Cannot identify the active MoonBit compiler: ${compilerVersion}`);
const core = join(process.env.MOON_HOME || join(homedir(),'.moon'),'lib','core');
const coreVersion = /^version\s*=\s*"([^"]+)"/m.exec(readFileSync(join(core,'moon.mod'),'utf8'))?.[1];
if (!coreVersion) throw new Error(`Cannot identify the active MoonBit core in ${core}`);
console.log(versionText.trim());
execFileSync('moon',['build','--target','js','--release'],{cwd:root,stdio:'inherit'});
const web = new URL('../web/', import.meta.url);
mkdirSync(web,{recursive:true});
copyFileSync(new URL('../_build/js/release/build/bridge/bridge.js',import.meta.url),new URL('mooninput.mjs',web));
copyFileSync(new URL('../LICENSE',import.meta.url),new URL('LICENSE.txt',web));
const readCore = name => readFileSync(join(core,name),'utf8').replaceAll('\r\n','\n');
writeFileSync(new URL('THIRD-PARTY-NOTICES.txt',web), readCore('NOTICE')+'\n'+readCore('LICENSE'));
let sourceCommit = null;
try { sourceCommit=execFileSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8'}).trim(); } catch {}
writeFileSync(new URL('build-info.json',web),JSON.stringify({version,toolchain,compilerVersion,coreVersion,moonVersion:versionText.trim(),sourceCommit,engineSha256:createHash('sha256').update(readFileSync(new URL('mooninput.mjs',web))).digest('hex')},null,2)+'\n');
console.log('Built MoonBit input engine and license notices.');
