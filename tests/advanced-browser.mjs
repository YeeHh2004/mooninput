import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import {startServer} from '../scripts/serve.mjs';
const engines=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const engine=process.env.BROWSER_ENGINE||'chromium';
if(!['chromium','firefox','webkit'].includes(engine))throw new Error('Unsupported BROWSER_ENGINE');
const server=await startServer();
let browser;
const checks=[];
function check(name,actual,expected){assert.deepEqual(actual,expected,name);checks.push(name);}
try{
  browser=await engines[engine].launch({headless:true,...(process.env.BROWSER_CHANNEL?{channel:process.env.BROWSER_CHANNEL}:{})});
  const page=await browser.newPage({viewport:{width:1440,height:1100}});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  await page.waitForFunction(()=>document.documentElement.dataset.ready==='true'&&document.documentElement.dataset.advancedReady==='true');
  const dynamic=page.locator('#adv-dynamic');
  await dynamic.pressSequentially('1234');
  check('dynamic short format',await dynamic.inputValue(),'12-34');
  check('dynamic exposes short branch',await page.locator('#adv-dynamic-active').textContent(),'short');
  await dynamic.pressSequentially('5');
  check('dynamic switches to long',await dynamic.inputValue(),'123-45');
  check('dynamic exposes long branch',await page.locator('#adv-dynamic-active').textContent(),'long');
  await dynamic.press('Backspace');
  check('dynamic deletion selects short again',await dynamic.inputValue(),'12-34');
  await dynamic.evaluate(el=>{
    el.setSelectionRange(0,el.value.length);
    const event=new Event('paste',{bubbles:true,cancelable:true});
    Object.defineProperty(event,'clipboardData',{value:{getData:()=> '123456'}});el.dispatchEvent(event);
  });
  check('dynamic paste selects full long branch',await dynamic.inputValue(),'123-456');
  const username=page.locator('#adv-regex');
  await username.pressSequentially('A');
  check('regex prefix stays editable',await username.inputValue(),'A');
  check('regex reports incomplete prefix',await page.locator('#adv-regex-status').getAttribute('data-state'),'incomplete');
  await username.pressSequentially('lice_7');
  check('regex accepts complete username',await page.locator('#adv-regex-value').textContent(),'Alice_7');
  await username.pressSequentially('!');
  check('regex rejects invalid insertion atomically',await username.inputValue(),'Alice_7');
  check('regex error is visible',(await page.locator('#adv-regex-error').textContent()).length>0,true);
  await page.locator('[data-adv-fill=time]').click();
  check('composite time display',await page.locator('#adv-time').inputValue(),'09:30');
  check('composite exposes named fields',await page.locator('#adv-time-fields').textContent(),'hour=09 · minute=30');
  const time=page.locator('#adv-time');await time.fill('');await time.pressSequentially('2');await time.pressSequentially('9');
  check('range rejects impossible hour prefix',await time.inputValue(),'2');
  await page.locator('[data-adv-fill=hex]').click();
  check('custom token normalizes hex',await page.locator('#adv-hex').inputValue(),'A1:B2:C3');
  const hex=page.locator('#adv-hex');await hex.focus();await hex.evaluate(el=>el.setSelectionRange(0,1));await hex.pressSequentially('g');
  check('custom token rejects non-hex replacement',await hex.inputValue(),'A1:B2:C3');
  await page.locator('[data-adv-fill=number]').click();
  check('locale number display',await page.locator('#adv-number').inputValue(),'1.234,50');
  check('locale number canonical exact value',await page.locator('#adv-number-value').textContent(),'1234.50');
  await page.locator('#adv-number').fill('10001');
  check('locale number bounds invalidate complete value',await page.locator('#adv-number-status').getAttribute('data-state'),'invalid');
  check('locale number invalid value cannot submit',await page.locator('#adv-number-value').textContent(),'—');
  await page.locator('[data-adv-fill=date]').click();
  check('configurable date display',await page.locator('#adv-date').inputValue(),'29/02/2024');
  check('configurable date ISO value',await page.locator('#adv-date-value').textContent(),'2024-02-29');
  await page.locator('#adv-date').fill('29022025');
  check('configurable date detects invalid leap day',await page.locator('#adv-date-status').getAttribute('data-state'),'invalid');
  const preset=page.locator('#adv-preset'),input=page.locator('#adv-config-input');
  async function applyPreset(key){await preset.selectOption(key);await page.locator('#adv-apply').click();}
  const state=async()=>JSON.parse(await page.locator('#adv-state').textContent());
  await applyPreset('repeat');await input.pressSequentially('ab12');
  check('workbench repeats arbitrary child blocks',(await state()).value,'AB12');
  check('workbench repeat returns numbered fields',(await state()).fields.map(field=>field.name),['0','1']);
  await applyPreset('enum');await input.pressSequentially('express');
  check('workbench enumeration normalizes canonical spelling',(await state()).value,'EXPRESS');
  await applyPreset('validate');await input.pressSequentially('AC1');
  check('workbench custom validation marks semantic invalid',(await state()).status,'invalid');
  await input.fill('AB1');check('workbench custom validation can be repaired',(await state()).value,'AB1');
  await applyPreset('presentation');
  check('workbench placeholders are visible',await input.inputValue(),'__-__');
  await input.pressSequentially('1234');
  check('workbench secure display keeps literal separator',await input.inputValue(),'●●-●●');
  check('workbench secure display retains raw value',(await state()).raw,'1234');
  const before=await state();
  await page.locator('#adv-config').fill('{"kind":"regex","source":"["}');await page.locator('#adv-apply').click();
  check('invalid rule configuration preserves editor state',await state(),before);
  check('invalid rule configuration is reported',await page.locator('#adv-config').getAttribute('aria-invalid'),'true');
  await page.locator('#adv-config').fill('{');await page.locator('#adv-apply').click();
  check('invalid JSON preserves visible input',await input.inputValue(),'●●-●●');
  await applyPreset('regex');await input.pressSequentially('Abc');await input.pressSequentially('d');
  await page.locator('#adv-undo').click();check('workbench undo uses field history',(await state()).raw,'Abc');
  await page.locator('#adv-redo').click();check('workbench redo uses field history',(await state()).raw,'Abcd');
  const events=await page.evaluate(async()=>{
    const {bindInput}=await import('./adapter.mjs');const element=document.createElement('input');document.body.append(element);
    let accepts=0,completes=0;
    const binding=bindInput(element,{kind:'pattern',pattern:'##'},{onAccept:()=>accepts++,onComplete:()=>completes++});
    binding.setValue('12');const failed=binding.updateOptions({pattern:'['});const preserved=binding.state.raw;
    const succeeded=binding.updateOptions({pattern:'###'});const updated=binding.state.status;
    binding.setValue('123');binding.destroy();element.remove();
    return {failed:failed.ok,preserved,succeeded:succeeded.ok,updated,accepts,completes};
  });
  check('option updates are atomic and expose accept-complete events',events,{failed:false,preserved:'12',succeeded:true,updated:'incomplete',accepts:3,completes:2});
  await page.locator('#adv-examples').scrollIntoViewIfNeeded();
  await mkdir(new URL('../dist/browser-screenshots/',import.meta.url),{recursive:true});
  const localPath=url=>url.pathname.replace(/^\/(\w:)/,'$1');
  await page.screenshot({path:localPath(new URL(`../dist/browser-screenshots/${engine}-advanced-desktop.png`,import.meta.url)),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  check('advanced mobile layout has no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:localPath(new URL(`../dist/browser-screenshots/${engine}-advanced-mobile.png`,import.meta.url)),fullPage:true});
  check('advanced examples have no browser exceptions',errors,[]);
  await writeFile(new URL(`../dist/advanced-${engine}-results.json`,import.meta.url),JSON.stringify({engine,checks:checks.length,passed:checks},null,2));
  console.log(`${engine} advanced browser checks passed: ${checks.length}`);
}finally{await browser?.close();await new Promise(resolve=>server.close(resolve));}
